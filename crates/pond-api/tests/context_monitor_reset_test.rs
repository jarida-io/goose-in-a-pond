fn delete_session_request(session_id: &str) -> Request<Body> {
    Request::builder()
        .method("DELETE")
        .uri(format!("/api/v1/sessions/{session_id}"))
        .header("Authorization", "Bearer test-token")
        .body(Body::empty())
        .unwrap()
}

/// Proxy for "nothing left": a session above 75% grants a compaction claim, an unseen one none.
#[tokio::test]
async fn deleting_a_session_clears_its_context_monitor_state() {
    let (app, state, _tmp) = make_app().await;

    let session = state
        .session_storage
        .create_session("p6-session".to_string())
        .await
        .expect("create session");

    // Saturate it the way a real turn would.
    state.context_monitor.record_turn(&session.id, 7000, 8192);
    let before = state.context_monitor.check_context_health(&session.id);
    assert!(
        before.should_compact,
        "fixture is not under pressure ({}%) - the assertion below would pass \
         vacuously against a session that was never tracked",
        before.utilization_pct,
    );

    let resp = app
        .oneshot(delete_session_request(&session.id))
        .await
        .unwrap();
    assert_eq!(resp.status(), StatusCode::NO_CONTENT);

    let after = state.context_monitor.check_context_health(&session.id);
    assert_eq!(
        after.utilization_pct, 0.0,
        "the deleted session's utilisation survived the delete",
    );
    assert!(
        !after.should_compact,
        "the deleted session still reports pressure",
    );
    assert!(
        !state.context_monitor.claim_compaction(&session.id),
        "a recycled session id would inherit the compaction cooldown of the \
         conversation it replaced",
    );
}
